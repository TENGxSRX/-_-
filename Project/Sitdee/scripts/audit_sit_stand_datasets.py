"""Audit available datasets for evidence needed by the CCTV hierarchy.

This is an evidence gate only.  It never downloads data or trains a model.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.posture_ai.data.dataset_registry import registry_as_dicts


def audit() -> dict:
    records = registry_as_dicts()
    sit_stand = []
    sitting_quality = []
    for record in records:
        labels = {str(value).casefold() for value in record["labels"]}
        compatible_rgb = bool(record["raw_rgb_available"]) and record["landmark_format"] in {
            "RGB video; MediaPipe-derived features generated by project pipeline",
            "RGB images with project-extracted pose features",
        }
        if {"stand", "standing"} & labels and compatible_rgb and record["supervised_training_allowed"]:
            sit_stand.append(record["dataset_name"])
        if record["supervised_training_allowed"] and compatible_rgb and {"correct", "incorrect", "healthy", "wrong"} & labels:
            sitting_quality.append(record["dataset_name"])
    return {
        "status": "STANDING_DATA_INSUFFICIENT" if not sit_stand else "STANDING_DATA_CANDIDATE_FOUND",
        "sitting_quality_status": "SITTING_POSTURE_DATA_INSUFFICIENT" if not sitting_quality else "SITTING_POSTURE_DATA_CANDIDATE_FOUND",
        "sit_stand_supervised_rgb_candidates": sit_stand,
        "sitting_quality_supervised_rgb_candidates": sitting_quality,
        "records": records,
        "training_performed": False,
        "decision": "Do not train the hierarchical activity or sitting-quality models from the current registry without source-backed labels and participant/session groups.",
    }


def write_report(path: Path, result: dict) -> None:
    lines = [
        "# Sit/stand และ sitting-quality dataset audit",
        "",
        f"สถานะ standing: **{result['status']}**",
        f"สถานะ sitting quality: **{result['sitting_quality_status']}**",
        "",
        "## ข้อสรุป",
        "",
        "ยังไม่มีชุดข้อมูล RGB/MediaPipe ที่มี label sit/stand และ participant/session grouping ที่ตรวจสอบได้เพียงพอสำหรับเทรน production model.",
        "จึงยังไม่ train activity classifier, sitting-quality classifier หรือ subtype classifier.",
        "",
        "## หลักฐานจาก registry",
        "",
        "| Dataset | RGB | label ที่พบ | ใช้ train ตอนนี้ | ข้อจำกัด |",
        "|---|---:|---|---:|---|",
    ]
    for record in result["records"]:
        labels = ", ".join(record["labels"]) or "NONE_VERIFIED"
        lines.append(f"| {record['dataset_name']} | {record['raw_rgb_available']} | {labels} | {record['supervised_training_allowed']} | {record['notes']} |")
    lines.extend([
        "",
        "## Engineering decision",
        "",
        "- MultiPosture ใช้เป็น direction expert เดิมเท่านั้น ไม่ใช่ sit/stand ground truth.",
        "- SitPose มี label `stand` แต่เป็นข้อมูล Kinect/depth และไม่มี grouping ที่พอสำหรับ CCTV RGB จึงเป็น reference เท่านั้น.",
        "- SitStraightNet เป็นภาพที่ยังไม่มี verified per-file labels.",
        "- ANYA เป็น pseudo-label/distribution audit เท่านั้น.",
        "- ต้องเก็บ CCTV ground truth แบบ human-labelled และใช้ participant/session grouped split ก่อนเริ่ม V5.",
        "",
    ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", default="reports/sit_stand_dataset_audit_th.md")
    parser.add_argument("--json", default="outputs/metrics/sit_stand_dataset_audit.json")
    args = parser.parse_args()
    result = audit()
    json_path = Path(args.json)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    write_report(Path(args.report), result)
    print(json.dumps({key: result[key] for key in ("status", "sitting_quality_status", "sit_stand_supervised_rgb_candidates", "sitting_quality_supervised_rgb_candidates")}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
