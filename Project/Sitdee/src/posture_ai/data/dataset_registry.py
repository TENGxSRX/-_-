@dataclass(frozen=True)
class DatasetRecord:
    dataset_name: str
    source: str
    provenance: str
    number_of_samples: int | None
    participant_count: int | None
    raw_rgb_available: bool | None
    landmark_format: str
    coordinate_system: str
    landmark_count: int | None
    labels: tuple[str, ...]
    label_semantics: str
    camera_view_information: str
    subject_id_availability: str
    trust_level: str
    supervised_training_allowed: bool
    notes: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


