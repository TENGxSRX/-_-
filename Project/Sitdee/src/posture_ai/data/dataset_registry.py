def get_dataset_record(dataset_name: str) -> DatasetRecord:
    wanted = str(dataset_name).casefold()
    for record in DATASET_REGISTRY:
        if record.dataset_name.casefold() == wanted:
            return record
    raise KeyError(f"Unknown dataset: {dataset_name}")


def registry_as_dicts() -> list[dict[str, Any]]:
    return [record.to_dict() for record in DATASET_REGISTRY]


